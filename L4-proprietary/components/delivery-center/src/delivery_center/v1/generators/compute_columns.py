def reorder_sign_columns(df):
    """按参考报表顺序排列签约 Sheet 列，重命名 ONES 列名→参考报表列名"""
    # 列名映射：ONES → 参考报表
    rename_map = {
        '合同开始日期': '合同起始日期',
    }
    df = df.rename(columns=rename_map)
    
    # 移除不需要的列（如立项年份）
    df = df.drop(columns=['立项年份'], errors='ignore')
    
    cols = get_sign_column_order()
    existing = [c for c in cols if c in df.columns]
    remaining = [c for c in df.columns if c not in cols]
    return df[existing + remaining]


def compute_poc_columns(df):
    """为 POC&提前实施 Sheet 添加计算列"""
    # POC 结构与签约类似，复用相同计算逻辑
    return compute_sign_columns(df)


def reorder_poc_columns(df):
    """按参考报表顺序排列 POC Sheet 列，重命名 ONES 列名→参考报表列名"""
    rename_map = {
        '合同开始日期': '合同起始日期',
    }
    df = df.rename(columns=rename_map)
    df = df.drop(columns=['立项年份'], errors='ignore')
    
    cols = get_sign_column_order()
    existing = [c for c in cols if c in df.columns]
    remaining = [c for c in df.columns if c not in cols]
    return df[existing + remaining]
