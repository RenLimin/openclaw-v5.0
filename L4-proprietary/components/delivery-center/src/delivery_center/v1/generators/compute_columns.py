"""
签约/POC Sheet 计算列生成器
参考报表有 83~84 列，ONES 导出只有 40 列，需要计算列 40+
"""
import pandas as pd


def compute_sign_columns(df):
    """为签约 Sheet 添加计算列，匹配参考报表的 83 列"""
    df = df.copy()
    
    # 按立项日期降序排序（匹配参考报表排序逻辑）
    df['_sort_date'] = pd.to_datetime(df['立项日期'], errors='coerce')
    df = df.sort_values('_sort_date', ascending=False, na_position='last')
    df = df.drop(columns=['_sort_date'])
    df = df.reset_index(drop=True)
    
    # 列40: 项目编号 → 从"所属项目"提取 SSXM-XXXX-XXXX-XXXX
    df['项目编号'] = df['所属项目'].str.extract(r'(SSXM-[^】]+)', expand=False)
    
    # 列41: 统计项目编号 → 同项目编号
    df['统计项目编号'] = df['项目编号']
    
    # 列42: 统计合同编号 → 销售合同编号
    df['统计合同编号'] = df['销售合同编号']
    
    # 列43: 合同归档年度
    df['合同归档年度'] = pd.to_datetime(df['合同归档日期'], errors='coerce').dt.year
    df['合同归档年度'] = df['合同归档年度'].fillna(0).astype(int).replace(0, '')
    
    # 列44-51: 履约项状态计数（每行根据"状态"字段计数）
    # 注意：列名必须与参考报表完全一致
    status_cols = {
        '实施未开始': '实施未开始',
        '义务已拆分': '义务已拆分',
        '实施进行中': '实施进行中',
        '实施已完成': '实施已完成',
        '交付邮件交接中': '交付邮件交接中',
        '交付邮件已归档': '交付邮件已归档',
        '验收文件交接中': '验收文件交接中',
        '验收文件已归档': '验收文件已归档',
    }
    for status, col_name in status_cols.items():
        df[col_name] = (df['状态'] == status).astype(int)
    
    # 列52: 履约项合计 = 列44-51的和
    df['履约项合计'] = df[list(status_cols.values())].sum(axis=1)
    
    # 列53: 校验（履约项合计 - 某个值，暂设为0）
    df['校验'] = 0
    
    # 列54: 项目统计状态
    df['项目统计状态'] = df['状态'].map({
        '实施未开始': '未实施',
        '义务已拆分': '未实施',
        '实施进行中': '未实施',
        '实施已完成': '已实施',
        '交付邮件交接中': '已实施',
        '交付邮件已归档': '已交付',
        '验收文件交接中': '已交付',
        '验收文件已归档': '已验收',
    }).fillna('')
    
    # 列55: 履约项统计状态（即，财报-交付/确收状态）
    df['履约项统计状态（即，财报-交付/确收状态）'] = df['状态'].map({
        '实施未开始': '1：正常交付',
        '义务已拆分': '1：正常交付',
        '实施进行中': '1：正常交付',
        '实施已完成': '4：正常验收',
        '交付邮件交接中': '1：正常交付',
        '交付邮件已归档': '4：正常验收',
        '验收文件交接中': '4：正常验收',
        '验收文件已归档': '7：正常服务',
    }).fillna('')
    
    # 列56-64: 状态分类计数（每行根据履约项统计状态计数）
    status_categories = [
        '1：正常交付', '2：应交未交', '3：交付异常', '4：正常验收',
        '5：应验未验', '6：验收异常', '7：正常服务', '8：应结未结', '9：已结项'
    ]
    for status in status_categories:
        df[status] = (df['履约项统计状态（即，财报-交付/确收状态）'] == status).astype(int)
    
    # 列65: 统计校验
    df['统计校验'] = 0
    
    # 列66: 项目验收状态（即，财报-验收状态）
    df['项目验收状态（即，财报-验收状态）'] = df['状态'].map({
        '实施未开始': '完全不可验收',
        '义务已拆分': '完全不可验收',
        '实施进行中': '完全不可验收',
        '实施已完成': '可完整验收',
        '交付邮件交接中': '可完整验收',
        '交付邮件已归档': '可完整验收',
        '验收文件交接中': '可部分验收',
        '验收文件已归档': '已验收',
    }).fillna('')
    
    # 列67: 基线-预估结项日期（计算后反填）
    df['基线-预估结项日期（计算后反填）'] = df['基线-预估结项日期']
    
    # 列68-75: 交付计划准确率/按时交付率（需要实际日期计算，暂设为默认值）
    # 注意：参考报表使用中文引号
    df['交付计划准确率\u201c差异\u201d'] = ''
    df['交付计划准确率\u201c提前/延后\u201d'] = ''
    df['交付计划准确率\u201c是否跨月\u201d'] = ''
    df['交付计划准确率-考核扣分'] = 0
    df['按时交付率\u201c差异\u201d'] = 0
    df['按时交付率\u201c提前/延后\u201d'] = ''
    df['按时交付率\u201c是否跨月\u201d'] = ''
    df['按时交付率-考核扣分'] = 0
    
    # 列76-78: 项目经理信息
    df['项目经理'] = df['负责人']
    df['项目经理所属部门'] = df['责任销售所属团队']
    df['销售团队-统计'] = df['责任销售所属团队']
    
    # 列79-82: 异常对比/处置状态/影响情况/交付说明
    df['异常项目对比'] = ''
    df['异常处置状态'] = ''
    df['异常影响情况'] = ''
    df['交付说明'] = ''
    
    return df


