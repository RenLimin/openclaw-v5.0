def build_legend_sheet(wb):
    """构建图例 Sheet"""
    ws = wb.create_sheet("图例")
    
    # 写列名（行0）
    for ci, name in enumerate(COLUMN_NAMES):
        if name:
            ws.cell(row=1, column=ci + 1, value=name)
            ws.cell(row=1, column=ci + 1).font = Font(bold=True)
    
    # 写项目经理-部门映射（行1-34）
    for ri, (pm, dept, center, remark) in enumerate(PM_DEPT_DATA, 2):
        ws.cell(row=ri, column=1, value=pm)
        ws.cell(row=ri, column=2, value=dept)
        ws.cell(row=ri, column=3, value=center)
        if remark:
            ws.cell(row=ri, column=4, value=remark)
    
    # 写考核项配置（行1-16，列5-9）
    for ri, (exam, bias, cross_month, over_15, weight) in enumerate(EXAM_CONFIG, 2):
        ws.cell(row=ri, column=6, value=exam)
        ws.cell(row=ri, column=7, value=bias)
        ws.cell(row=ri, column=8, value=cross_month)
        ws.cell(row=ri, column=9, value=over_15)
        ws.cell(row=ri, column=10, value=weight)
    
    # 写状态映射（行1-8，列12-23）
    for ri, (status, cat, _, _, _, _, item_status, proj_status, finance_del, finance_acc) in enumerate(STATUS_MAP, 2):
        ws.cell(row=ri, column=13, value=status)
        ws.cell(row=ri, column=14, value=cat)
        ws.cell(row=ri, column=21, value=item_status)
        ws.cell(row=ri, column=22, value=proj_status)
        ws.cell(row=ri, column=23, value=finance_del)
        ws.cell(row=ri, column=24, value=finance_acc)
    
    # 写销售团队映射（行1-18，列26-27）
    for ri, (team, stat_team) in enumerate(SALES_TEAM_MAP, 2):
        ws.cell(row=ri, column=27, value=team)
        ws.cell(row=ri, column=28, value=stat_team)
    
    # 写不合格原因（行1-3，列29-31）
    for ri, (cross, rev_fail, acc_fail) in enumerate(REASONS, 2):
        ws.cell(row=ri, column=30, value=cross)
        ws.cell(row=ri, column=31, value=rev_fail)
        ws.cell(row=ri, column=32, value=acc_fail)
    
    print("  ✅ 图例 Sheet")
    return ws


