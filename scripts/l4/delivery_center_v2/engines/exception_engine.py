def build_exception_df(df_exc_raw: pd.DataFrame, df_sign: pd.DataFrame) -> pd.DataFrame:
    """
    构建异常项目完整 DataFrame（38 列）

    从 df_sign 里关联出项目经理、项目经理团队、验收状态等信息
    """
    # 先取核心字段 — 本来 ONES 导出就有这些了，直接用
    df = df_exc_raw.copy()

    # 关联项目经理 → 从签约表取
    sign_lookup = df_sign.set_index("销售合同编号")["项目经理"]
    df["项目经理"] = df["销售合同编号"].map(sign_lookup.get)

    # 关联项目经理部门 → 从签约表取
    dept_lookup = df_sign.set_index("销售合同编号")["项目经理所属部门"]
    df["项目经理团队"] = df["销售合同编号"].map(dept_lookup.get)

    # 关联验收状态 → 从签约表取
    status_lookup = df_sign.set_index("销售合同编号")["项目验收状态（即，财报-验收状态）"]
    df["项目验收状态"] = df["销售合同编号"].map(status_lookup.get)

    # 确保列顺序正确
    expected_cols = [
        "BI履约ID",
        "最终用户名称",
        "客户名称",
        "责任销售（履约项）",
        "责任销售所属团队",
        "负责人",
        "所属项目",
        "项目类型(概览)",
        "项目状态",
        "立项日期",
        "基线-预估结项日期",
        "实际结项日期",
        "销售合同编号",
        "合同名称",
        "直签或代理",
        "合同归档日期",
        "合同起始日期",
        "合同结束日期",
        "交付服务开始日期",
        "交付服务结束日期",
        "合同验收条款",
        "验收时点",
        "验收方式",
        "标题",
        "标准产品/服务序号",
        "履约类型",
        "所属产线",
        "状态",
        "履约项异常/变更类型",
        "履约项优先级",
        "预估交付完成日期",
        "预算-预估交付完成日期",
        "交付邮件发送日期",
        "实际服务/授权开始日期",
        "实际服务/授权结束日期",
        "预估验收完成日期",
        "预算-预估验收完成日期",
        "备注",
        "PMO备注",
        "ID",
        "事业部（区域）",
        "事业部负责人",
        "异常报备日期",
        "预估异常处置完成日期",
        "异常归档日期",
        "异常影响情况",
        "异常项目-类别",
        "异常项目-处置方案",
        "异常处置方案-影响",
        "交付说明（异常履约项统计类别）",
        "交付说明（履约项交付情况、合同交付条款）",
        "交付中心反馈",
        "营销中心反馈",
        "项目异常内容",
        "预估金额",
        "项目经理",
        "项目经理团队",
        "项目验收状态",
    ]

    # 过滤存在的列（有些列可能因为数据缺失没有）
    actual_cols = [c for c in expected_cols if c in df.columns]
    df = df[actual_cols]

    return df